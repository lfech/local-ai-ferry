"""Bash completion for loaf, generated from the command tables so that it follows the CLI.

A local installation puts the script where bash-completion loads it on first use. The Debian package
installs the same script system-wide and removes it with the package.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import shlex

from . import assets, docs, locks, resources, transfer


MARKER = "# loaf Bash completion"
SYSTEM_PATH = Path("/usr/share/bash-completion/completions/loaf")
BASH_COMPLETION = Path("/usr/share/bash-completion/bash_completion")
DIRECTORY_OPTIONS = ("--project-dir", "--config-dir", "--backup-dir")
TOP = "."


def user_path() -> Path:
    """The per-user directory that bash-completion searches before the system one."""
    configured = os.environ.get("BASH_COMPLETION_USER_DIR", "").split(":")[0]
    base = Path(configured) if configured else locks.data_home() / "bash-completion"
    return base / "completions/loaf"


def words() -> tuple[dict[str, list[str]], dict[str, list[str]], dict[str, str | None]]:
    """Positional words and options per command, and each option value's kind: directory, file or none."""
    from . import cli

    arguments = {
        TOP: list(cli.COMMAND_HELP),
        "setup": ["all", *cli.SETUP_PARTS, "tests"], "install": ["all", *cli.SETUP_PARTS, "tests"],
        "package": list(cli.PACKAGE_SCRIPTS),
        "backup": [*transfer.TYPES, *transfer.ALIASES], "restore": [*transfer.TYPES, *transfer.ALIASES],
        "docs": [*docs.guides(), docs.MANUAL],
        "run": list(cli.SERVING), "stop": list(cli.SERVING), "restart": list(cli.SERVING),
        "docker rm": list(resources.SELECTABLE),
    }
    options = {TOP: list(cli.GLOBAL_OPTIONS)}
    for command, details in cli.COMMAND_HELP.items():
        options[command] = [*details.options, *cli.GLOBAL_OPTIONS]
        subcommands = cli.SUBCOMMAND_HELP.get(command, {})
        if subcommands:
            arguments[command] = list(subcommands)
        for subcommand, sub in subcommands.items():
            options[f"{command} {subcommand}"] = [*sub.options, *cli.GLOBAL_OPTIONS]
    parser = argparse.ArgumentParser(add_help=False)
    cli.add_options(parser)
    values = {}
    for action in parser._actions:
        if action.metavar:
            flag = action.option_strings[-1]
            values[flag] = "directory" if flag in DIRECTORY_OPTIONS else "file" if action.metavar == "PATH" else None
    return arguments, options, values


def script(*, system: bool = False) -> str:
    from . import cli

    arguments, options, values = words()

    def table(name: str, entries: dict[str, list[str]]) -> str:
        rows = (f"        [{shlex.quote(key)}]={shlex.quote(' '.join(items))}" for key, items in entries.items())
        return f"    local -A {name}=(\n" + "\n".join(rows) + "\n    )"

    def flags(kind: str | None) -> str:
        return "|".join(flag for flag, value in values.items() if value == kind)

    removal = "It is removed with the Debian package." if system else "Remove it with: loaf completion remove"
    return f"""\
{MARKER}, generated by loaf {assets.release_version()}. {removal}
_loaf() {{
    local cur=${{COMP_WORDS[COMP_CWORD]}} prev=${{COMP_WORDS[COMP_CWORD-1]}} key={TOP} word i
{table("options", options)}
{table("arguments", arguments)}
    # Bash splits --name=value at the equals sign.
    if [[ $cur == = ]]; then
        cur=
    elif [[ $prev == = && $COMP_CWORD -ge 2 ]]; then
        prev=${{COMP_WORDS[COMP_CWORD-2]}}
    fi
    case $prev in
        {flags("directory")})
            compopt -o filenames
            mapfile -t COMPREPLY < <(compgen -d -- "$cur")
            return ;;
        {flags("file")})
            compopt -o filenames
            mapfile -t COMPREPLY < <(compgen -f -- "$cur")
            return ;;
        {flags(None)})
            COMPREPLY=()
            return ;;
    esac
    # The command, and for {', '.join(cli.SUBCOMMAND_HELP)} also its subcommand, select the words.
    for ((i = 1; i < COMP_CWORD; i++)); do
        word=${{COMP_WORDS[i]}}
        case $word in
            {"|".join(values)})
                [[ ${{COMP_WORDS[i+1]}} == = ]] && ((i++))
                ((i++)) ;;
            -*|=) ;;
            *)
                if [[ $key == {TOP} ]]; then
                    key=$word
                elif [[ $key != *" "* && " {' '.join(cli.SUBCOMMAND_HELP)} " == *" $key "* ]]; then
                    key="$key $word"
                fi ;;
        esac
    done
    [[ -n ${{options[$key]+set}} ]] || key=${{key%% *}}
    [[ -n ${{options[$key]+set}} ]] || key={TOP}
    # Without positional words left, offer the options.
    if [[ $cur == -* || -z ${{arguments[$key]-}} ]]; then
        mapfile -t COMPREPLY < <(compgen -W "${{options[$key]}}" -- "$cur")
    else
        mapfile -t COMPREPLY < <(compgen -W "${{arguments[$key]}}" -- "$cur")
    fi
}}
complete -F _loaf loaf
"""


def owned(path: Path) -> bool:
    if path.is_symlink() or not path.is_file():
        return False
    with path.open(encoding="utf-8", errors="replace") as source:
        return source.readline().startswith(MARKER)


def install() -> str:
    if assets.debian_package():
        return f"The loaf Debian package provides Bash completion in {SYSTEM_PATH}. Nothing to install."
    target = user_path()
    if (target.exists() or target.is_symlink()) and not owned(target):
        raise OSError(f"{target} exists and was not created by loaf. Remove it first.")
    target.parent.mkdir(parents=True, exist_ok=True)
    staging = target.with_name(f".{target.name}.tmp")
    staging.write_text(script(), encoding="utf-8")
    staging.replace(target)
    message = f"Installed Bash completion in {target}. Open a new shell to use it."
    if not BASH_COMPLETION.is_file():
        message += ("\nbash-completion is missing. Install the Debian package bash-completion, "
                    f"or load the file from ~/.bashrc:\n  source {shlex.quote(str(target))}")
    return message


def remove() -> str:
    target = user_path()
    if not (target.exists() or target.is_symlink()):
        message = f"No loaf Bash completion in {target}."
    elif not owned(target):
        raise OSError(f"{target} was not created by loaf. It stays in place.")
    else:
        target.unlink()
        message = f"Removed {target}. Open a new shell to stop completing loaf."
    if assets.debian_package():
        message += f"\nThe Debian package keeps {SYSTEM_PATH} until the package is removed."
    return message
